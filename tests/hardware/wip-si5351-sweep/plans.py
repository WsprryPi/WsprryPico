"""Original fixed-tone planner using AN619 rev. 0.8 equations; no RF access."""
from fractions import Fraction
from pathlib import Path
import json

POINTS = [('2200m',137500),('630m',475700),('160m',1838100),('80m',3570100),
          ('60m',5288700),('40m',7050000),('30m',10140200),('20m',14097100),
          ('17m',18106100),('15m',21096100),('12m',24926100),('10m',28126100),
          ('8m',40001000),('6m',50294500),('5m',60001000),('4m',70400000),
          ('2m',144490500)]

def pack(ratio, r=0):
    a=ratio.numerator//ratio.denominator
    b=ratio.numerator-a*ratio.denominator;c=ratio.denominator
    d=(128*b)//c;p1=128*a+d-512;p2=128*b-c*d;p3=c
    assert 0<=p1<2**18 and 0<=p2<2**20 and 1<=p3<2**20
    return [p3>>8&255,p3&255,(p1>>16&3)|(r<<4),p1>>8&255,p1&255,
            ((p3>>16&15)<<4)|(p2>>16&15),p2>>8&255,p2&255]

def unpack(v):
    p1=((v[2]&3)<<16)|(v[3]<<8)|v[4]
    p2=((v[5]&15)<<16)|(v[6]<<8)|v[7]
    p3=((v[5]>>4)<<16)|(v[0]<<8)|v[1]
    return Fraction(p1+512,128)+Fraction(p2,128*p3)

def plans():
    out=[]
    for band,hz in POINTS:
        r=0
        if hz>112500000:
            ms=Fraction(6);pll=Fraction(hz*6,25000000).limit_denominator(1048575)
        else:
            pll=Fraction(36)
            while Fraction(900000000,hz*2**r)>900:r+=1
            ms=Fraction(900000000,hz*2**r).limit_denominator(1048575)
        assert 600000000<=25000000*pll<=900000000 and r<=7
        assert ms==6 or 8<=ms<=900
        pp=pack(pll);mp=pack(ms,r)
        actual=25000000*unpack(pp)/unpack(mp)/2**((mp[2]>>4)&7)
        error=float(actual-hz)
        assert abs(error)<0.001,(band,error)
        out.append(dict(band=band,hz=hz,pll=pp,ms=mp,
                        control=(0x4c if ms.denominator==1 and ms.numerator%2==0 else 0x0c) | (3 if band in ('2200m','630m') else 0),
                        pll_control=0xc0 if pll.denominator==1 and pll.numerator%2==0 else 0x80,
                        realized_hz=float(actual),error_hz=error,r_divider=2**r))
    return out

if __name__=='__main__':
    rows=plans();here=Path(__file__).parent
    header=['// SPDX-License-Identifier: MIT','// Generated by plans.py; do not edit.','#pragma once',
            '#include <cstdint>','struct Plan { const char* band; uint32_t hz; uint8_t pll[8], ms[8], control, pll_control; };',
            'constexpr Plan plans[]{']
    for p in rows:
        header.append('    {"%s", %d, {%s}, {%s}, %d, %d},' % (p['band'],p['hz'],
                      ','.join(map(str,p['pll'])),','.join(map(str,p['ms'])),p['control'],p['pll_control']))
    header.append('};');(here/'plans.hpp').write_text('\n'.join(header)+'\n')
    (here/'plans.json').write_text(json.dumps(rows,indent=2)+'\n')
    print('Verified %d plans; max arithmetic error %.9g Hz' % (len(rows),max(abs(p['error_hz']) for p in rows)))
